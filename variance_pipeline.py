import pandas as pd
from scipy import stats

def run_ledgerguard_audit(file_path: str, z_threshold: float = 2.5):
    print("[+] Loading Trial Balance ERP export...")
    # Ingesting trial balance data (expects columns: account_code, account_name, category, balance)
    tb = pd.read_excel(file_path)

    print("[+] Calculating statistical Z-scores for balance fluctuations...")
    tb["z_score"] = stats.zscore(tb["balance"].fillna(0))

    print(f"[+] Filtering anomalies where absolute Z-score > {z_threshold}...")
    anomalies = tb[abs(tb["z_score"]) > z_threshold].copy()

    print(f"[!] Flagged {len(anomalies)} high-risk accounts requiring substantive testing.")

    # Simulating Gemini AI integration for audit procedure generation
    print("[+] Engaging Gemini API to draft substantive audit procedures...")
    for idx, row in anomalies.iterrows():
        account_name = row['account_name']
        variance_val = row['balance']
        z_val = row['z_score']

        # Simulated AI-generated workpaper note
        ai_memo = (
            f"AUDIT PROCEDURE MEMO:\n"
            f"Account: {account_name} | Balance: {variance_val:,.2f} | Z-Score: {z_val:.2f}\n"
            f"Recommended Test: Obtain sub-ledger detail, perform vouching for transactions > materiality threshold, "
            f"and inspect management corroborating explanations for unusual variance per FRS 102 / IFRS requirements."
        )
        anomalies.loc[idx, 'ai_audit_procedure'] = ai_memo

    # Exporting results for audit team review
    output_path = "LedgerGuard_Audit_Exceptions_Report.csv"
    anomalies.to_csv(output_path, index=False)
    print(f"[✓] Analysis complete. Audit exceptions report saved to {output_path}")

    return anomalies

